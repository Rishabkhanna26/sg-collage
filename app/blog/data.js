export function getBlogPostBySlug(slug) {
  return blogPosts.find((p) => p.slug === slug) ?? null;
}

export function getRelatedPosts(slug) {
  const current = getBlogPostBySlug(slug);
  if (!current) return [];
  return blogPosts
    .filter((p) => p.slug !== slug && p.category === current.category)
    .slice(0, 3);
}
